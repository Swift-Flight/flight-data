@Suite("SchemaBuilder: drop/rename/alter")
struct AlterTests {
    @Test func dropTableVariants() {
        let schema = SchemaBuilder()
        schema.dropTable("users")
        schema.dropTable("users", ifExists: true, cascade: true)
        #expect(schema.statements[0] == "DROP TABLE \"users\"")
        #expect(schema.statements[1] == "DROP TABLE IF EXISTS \"users\" CASCADE")
    }

    @Test func renameTable() {
        let schema = SchemaBuilder()
        schema.renameTable("old", to: "new")
        #expect(schema.statements == ["ALTER TABLE \"old\" RENAME TO \"new\""])
    }

    @Test func alterTableEmitsOneStatementPerActionInOrder() {
        let schema = SchemaBuilder()
        schema.alterTable("users") { t in
            t.text("bio").notNull().default("")
            t.addColumn("nick", .text, ifNotExists: true)
            t.dropColumn("legacy", ifExists: true, cascade: true)
            t.renameColumn("email", to: "email_address")
            t.setDefault("bio", .string("hi"))
            t.dropDefault("bio")
            t.setNotNull("bio")
            t.dropNotNull("bio")
            t.setDataType("count", .bigint, using: "count::bigint")
            t.addUnique(["email_address"], name: "users_email_key")
            t.addCheck("length(bio) < 500")
            t.addPrimaryKey(["id"])
            t.addForeignKey(["team_id"], references: "teams", onDelete: .cascade)
            t.dropConstraint("users_email_key", ifExists: true)
        }
        #expect(
            schema.statements == [
                "ALTER TABLE \"users\" ADD COLUMN \"bio\" TEXT NOT NULL DEFAULT ''",
                "ALTER TABLE \"users\" ADD COLUMN IF NOT EXISTS \"nick\" TEXT",
                "ALTER TABLE \"users\" DROP COLUMN IF EXISTS \"legacy\" CASCADE",
                "ALTER TABLE \"users\" RENAME COLUMN \"email\" TO \"email_address\"",
                "ALTER TABLE \"users\" ALTER COLUMN \"bio\" SET DEFAULT 'hi'",
                "ALTER TABLE \"users\" ALTER COLUMN \"bio\" DROP DEFAULT",
                "ALTER TABLE \"users\" ALTER COLUMN \"bio\" SET NOT NULL",
                "ALTER TABLE \"users\" ALTER COLUMN \"bio\" DROP NOT NULL",
                "ALTER TABLE \"users\" ALTER COLUMN \"count\" TYPE BIGINT USING count::bigint",
                "ALTER TABLE \"users\" ADD CONSTRAINT \"users_email_key\" UNIQUE (\"email_address\")",
                "ALTER TABLE \"users\" ADD CHECK (length(bio) < 500)",
                "ALTER TABLE \"users\" ADD PRIMARY KEY (\"id\")",
                "ALTER TABLE \"users\" ADD FOREIGN KEY (\"team_id\") REFERENCES \"teams\" (\"id\") ON DELETE CASCADE",
                "ALTER TABLE \"users\" DROP CONSTRAINT IF EXISTS \"users_email_key\"",
            ])
    }

    @Test func lateModifiersOnAddedColumnAreCaptured() {
        // Modifiers applied after other actions still land on the right ADD COLUMN.
        let schema = SchemaBuilder()
        schema.alterTable("t") { t in
            let bio = t.text("bio")
            t.dropColumn("old")
            bio.notNull()
        }
        #expect(schema.statements[0] == "ALTER TABLE \"t\" ADD COLUMN \"bio\" TEXT NOT NULL")
        #expect(schema.statements[1] == "ALTER TABLE \"t\" DROP COLUMN \"old\"")
    }
}

@Suite("SchemaBuilder: indexes and extensions")
struct IndexTests {
    @Test func defaultNameUniquePartialAndMethod() {
        let schema = SchemaBuilder()
        schema.createIndex(on: "users", columns: ["email"])
        schema.createIndex(on: "users", columns: ["a", "b"], unique: true)
        schema.createIndex(
            on: "users", columns: ["email"], name: "custom_idx", ifNotExists: true,
            using: .gin, where: "deleted_at IS NULL")
        #expect(schema.statements[0] == "CREATE INDEX \"users_email_idx\" ON \"users\" (\"email\")")
        #expect(
            schema.statements[1]
                == "CREATE UNIQUE INDEX \"users_a_b_idx\" ON \"users\" (\"a\", \"b\")")
        #expect(
            schema.statements[2]
                == "CREATE INDEX IF NOT EXISTS \"custom_idx\" ON \"users\" USING GIN (\"email\") WHERE deleted_at IS NULL"
        )
    }

    @Test("a concurrent build defaults to IF NOT EXISTS so a retry can make progress")
    func concurrentIndexes() {
        let schema = SchemaBuilder()
        schema.createIndex(on: "users", columns: ["email"], concurrently: true)
        schema.dropIndex("users_email_idx", concurrently: true, ifExists: true)
        // A failed CONCURRENTLY build strands an INVALID index under this name,
        // and the migration was not in a transaction, so nothing rolled it back.
        // Without IF NOT EXISTS the retry dies on "relation already exists".
        #expect(
            schema.statements[0]
                == "CREATE INDEX CONCURRENTLY IF NOT EXISTS \"users_email_idx\" ON \"users\" (\"email\")")
        #expect(schema.statements[1] == "DROP INDEX CONCURRENTLY IF EXISTS \"users_email_idx\"")
    }

    @Test("the concurrent IF NOT EXISTS default can be declined explicitly")
    func concurrentIndexOptOut() {
        let schema = SchemaBuilder()
        schema.createIndex(on: "users", columns: ["email"], concurrently: true, ifNotExists: false)
        #expect(
            schema.statements[0]
                == "CREATE INDEX CONCURRENTLY \"users_email_idx\" ON \"users\" (\"email\")")
    }

    @Test("a non-concurrent build still defaults to plain CREATE INDEX")
    func nonConcurrentIndexUnchanged() {
        let schema = SchemaBuilder()
        schema.createIndex(on: "users", columns: ["email"])
        #expect(
            schema.statements[0]
                == "CREATE INDEX \"users_email_idx\" ON \"users\" (\"email\")")
    }

    @Test func indexNameStripsSchemaQualification() {
        let schema = SchemaBuilder()
        schema.createIndex(on: "audit.events", columns: ["at"])
        #expect(
            schema.statements[0]
                == "CREATE INDEX \"events_at_idx\" ON \"audit\".\"events\" (\"at\")")
    }

    @Test func extensions() {
        let schema = SchemaBuilder()
        schema.createExtension("pgcrypto")
        schema.createExtension("citext", ifNotExists: false)
        schema.dropExtension("citext", ifExists: true)
        #expect(schema.statements[0] == "CREATE EXTENSION IF NOT EXISTS \"pgcrypto\"")
        #expect(schema.statements[1] == "CREATE EXTENSION \"citext\"")
        #expect(schema.statements[2] == "DROP EXTENSION IF EXISTS \"citext\"")
    }
}

@Suite("SchemaBuilder: raw")
struct RawTests {
    @Test func rawIsVerbatimAndOrdered() {
        let schema = SchemaBuilder()
        schema.raw("UPDATE users SET a = 1")
        schema.dropTable("t")
        schema.raw("SELECT pg_notify('x', 'y')")
        #expect(
            schema.statements == [
                "UPDATE users SET a = 1",
                "DROP TABLE \"t\"",
                "SELECT pg_notify('x', 'y')",
            ])
    }

    @Test func trailingSemicolonsAndWhitespaceStripped() {
        let schema = SchemaBuilder()
        schema.raw("  DROP TABLE x;  ")
        schema.raw("DROP TABLE y;;\n")
        #expect(schema.statements == ["DROP TABLE x", "DROP TABLE y"])
    }

    @Test func internalSemicolonsPreserved() {
        let schema = SchemaBuilder()
        let function = """
            CREATE FUNCTION f() RETURNS void AS $$
            BEGIN
                UPDATE t SET a = 1;
            END;
            $$ LANGUAGE plpgsql
            """
        schema.raw(function)
        #expect(schema.statements == [function])
    }

    @Test func emptyStatementsIgnored() {
        let schema = SchemaBuilder()
        schema.raw("")
        schema.raw("   ;  ")
        #expect(schema.statements.isEmpty)
    }

    @Test("a default index name is truncated to Postgres' identifier limit")
    func longIndexNamesAreTruncatedDistinctly() {
        let table = String(repeating: "a", count: 50)
        let schema = SchemaBuilder()
        schema.createIndex(on: table, columns: [String(repeating: "b", count: 30)])
        schema.createIndex(on: table, columns: [String(repeating: "c", count: 30)])

        let names = schema.statements.map { statement -> String in
            // `CREATE INDEX "name" ON …`
            let afterIndex = statement.drop(while: { $0 != "\"" }).dropFirst()
            return String(afterIndex.prefix(while: { $0 != "\"" }))
        }
        for name in names {
            #expect(
                name.utf8.count <= 63,
                "Postgres truncates past 63 bytes silently; \(name.utf8.count) bytes does not fit")
        }
        // The hazard is not the length, it is two long names colliding after
        // the server truncates them — the second CREATE INDEX then fails, or an
        // IF NOT EXISTS one quietly does nothing.
        #expect(names[0] != names[1], "names sharing a long prefix must stay distinct")
    }

    @Test("DefaultValue.generatedUUID renders the builtin")
    func generatedUUIDDefault() {
        let schema = SchemaBuilder()
        schema.createTable("t") { t in
            t.uuid("id").primaryKey().default(.generatedUUID)
        }
        #expect(schema.statements[0].contains("DEFAULT gen_random_uuid()"))
    }
}
