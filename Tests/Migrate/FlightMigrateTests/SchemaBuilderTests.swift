@Suite("SchemaBuilder: createTable")
struct CreateTableTests {
    @Test func designDocumentExample() {
        let schema = SchemaBuilder()
        schema.createTable("users") { t in
            t.uuid("id").primaryKey().default(.raw("gen_random_uuid()"))
            t.text("email").notNull().unique()
            t.timestamptz("created_at").notNull().default(.now)
        }
        #expect(
            schema.statements == [
                """
                CREATE TABLE "users" (
                    "id" UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                    "email" TEXT NOT NULL UNIQUE,
                    "created_at" TIMESTAMPTZ NOT NULL DEFAULT now()
                )
                """
            ])
    }

    @Test func modifierOrderIsCanonicalRegardlessOfChainOrder() {
        let a = SchemaBuilder()
        a.createTable("t") { t in t.text("c").default(.now).unique().notNull().primaryKey() }
        let b = SchemaBuilder()
        b.createTable("t") { t in t.text("c").primaryKey().notNull().unique().default(.now) }
        #expect(a.statements == b.statements)
    }

    @Test func ifNotExists() {
        let schema = SchemaBuilder()
        schema.createTable("t", ifNotExists: true) { t in t.integer("x") }
        #expect(schema.statements[0].hasPrefix("CREATE TABLE IF NOT EXISTS \"t\""))
    }

    @Test func columnTypes() {
        let schema = SchemaBuilder()
        schema.createTable("t") { t in
            t.smallint("a")
            t.bigint("b")
            t.boolean("c")
            t.real("d")
            t.doublePrecision("e")
            t.date("f")
            t.time("g")
            t.timestamp("h")
            t.interval("i")
            t.json("j")
            t.jsonb("k")
            t.bytea("l")
            t.inet("m")
            t.varchar("n", limit: 255)
            t.varchar("o")
            t.char("p", limit: 2)
            t.numeric("q", precision: 12, scale: 2)
            t.numeric("r", precision: 8)
            t.numeric("s")
            t.column("u", .array(of: .text))
            t.column("v", .custom("tsvector"))
        }
        let sql = schema.statements[0]
        #expect(sql.contains("\"a\" SMALLINT"))
        #expect(sql.contains("\"b\" BIGINT"))
        #expect(sql.contains("\"c\" BOOLEAN"))
        #expect(sql.contains("\"d\" REAL"))
        #expect(sql.contains("\"e\" DOUBLE PRECISION"))
        #expect(sql.contains("\"f\" DATE"))
        #expect(sql.contains("\"g\" TIME"))
        #expect(sql.contains("\"h\" TIMESTAMP,"))
        #expect(sql.contains("\"i\" INTERVAL"))
        #expect(sql.contains("\"j\" JSON,"))
        #expect(sql.contains("\"k\" JSONB"))
        #expect(sql.contains("\"l\" BYTEA"))
        #expect(sql.contains("\"m\" INET"))
        #expect(sql.contains("\"n\" VARCHAR(255)"))
        #expect(sql.contains("\"o\" VARCHAR,"))
        #expect(sql.contains("\"p\" CHAR(2)"))
        #expect(sql.contains("\"q\" NUMERIC(12, 2)"))
        #expect(sql.contains("\"r\" NUMERIC(8)"))
        #expect(sql.contains("\"s\" NUMERIC,"))
        #expect(sql.contains("\"u\" TEXT[]"))
        #expect(sql.contains("\"v\" tsvector"))
    }

    @Test func defaultValueRendering() {
        let schema = SchemaBuilder()
        schema.createTable("t") { t in
            t.text("a").default("it's")
            t.integer("b").default(42)
            t.doublePrecision("c").default(2.5)
            t.boolean("d").default(true)
            t.boolean("e").default(false)
            t.text("f").default(.null)
            t.jsonb("g").default(.raw("'{}'::jsonb"))
        }
        let sql = schema.statements[0]
        #expect(sql.contains("\"a\" TEXT DEFAULT 'it''s'"))
        #expect(sql.contains("\"b\" INTEGER DEFAULT 42"))
        #expect(sql.contains("\"c\" DOUBLE PRECISION DEFAULT 2.5"))
        #expect(sql.contains("\"d\" BOOLEAN DEFAULT TRUE"))
        #expect(sql.contains("\"e\" BOOLEAN DEFAULT FALSE"))
        #expect(sql.contains("\"f\" TEXT DEFAULT NULL"))
        #expect(sql.contains("\"g\" JSONB DEFAULT '{}'::jsonb"))
    }

    @Test func identityColumns() {
        let schema = SchemaBuilder()
        schema.createTable("t") { t in
            t.bigint("id").generatedAlwaysAsIdentity().primaryKey()
            t.bigint("alt").generatedByDefaultAsIdentity()
        }
        let sql = schema.statements[0]
        #expect(sql.contains("\"id\" BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY"))
        #expect(sql.contains("\"alt\" BIGINT GENERATED BY DEFAULT AS IDENTITY"))
    }

    @Test func columnChecksAndReferences() {
        let schema = SchemaBuilder()
        schema.createTable("t") { t in
            t.integer("age").check("age >= 0")
            t.uuid("user_id").notNull()
                .references("users", onDelete: .cascade, onUpdate: .restrict)
            t.uuid("org_id").references("orgs", "org_key", onDelete: .setNull)
        }
        let sql = schema.statements[0]
        #expect(sql.contains("\"age\" INTEGER CHECK (age >= 0)"))
        #expect(
            sql.contains(
                "\"user_id\" UUID NOT NULL REFERENCES \"users\" (\"id\") ON DELETE CASCADE ON UPDATE RESTRICT"
            ))
        #expect(
            sql.contains("\"org_id\" UUID REFERENCES \"orgs\" (\"org_key\") ON DELETE SET NULL"))
    }

    @Test func tableConstraints() {
        let schema = SchemaBuilder()
        schema.createTable("t") { t in
            t.uuid("a")
            t.uuid("b")
            t.primaryKey(["a", "b"])
            t.unique(["a", "b"], name: "t_a_b_key")
            t.unique(["b"])
            t.check("a <> b", name: "distinct_ab")
            t.foreignKey(["a", "b"], references: "other", ["x", "y"], onDelete: .cascade)
        }
        let sql = schema.statements[0]
        #expect(sql.contains("    PRIMARY KEY (\"a\", \"b\")"))
        #expect(sql.contains("    CONSTRAINT \"t_a_b_key\" UNIQUE (\"a\", \"b\")"))
        #expect(sql.contains("    UNIQUE (\"b\")"))
        #expect(sql.contains("    CONSTRAINT \"distinct_ab\" CHECK (a <> b)"))
        #expect(
            sql.contains(
                "    FOREIGN KEY (\"a\", \"b\") REFERENCES \"other\" (\"x\", \"y\") ON DELETE CASCADE"
            ))
    }

    @Test func timestampsSugar() {
        let schema = SchemaBuilder()
        schema.createTable("t") { t in t.timestamps() }
        let sql = schema.statements[0]
        #expect(sql.contains("\"created_at\" TIMESTAMPTZ NOT NULL DEFAULT now()"))
        #expect(sql.contains("\"updated_at\" TIMESTAMPTZ NOT NULL DEFAULT now()"))
    }

    @Test func schemaQualifiedAndQuotedIdentifiers() {
        let schema = SchemaBuilder()
        schema.createTable("analytics.events") { t in
            t.text("weird\"name")
        }
        let sql = schema.statements[0]
        #expect(sql.hasPrefix("CREATE TABLE \"analytics\".\"events\""))
        #expect(sql.contains("\"weird\"\"name\" TEXT"))
    }
